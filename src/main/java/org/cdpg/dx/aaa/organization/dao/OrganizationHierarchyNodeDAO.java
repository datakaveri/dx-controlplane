package org.cdpg.dx.aaa.organization.dao;

import io.vertx.core.Future;
import java.util.List;
import java.util.UUID;
import org.cdpg.dx.aaa.organization.models.OrganizationHierarchyNode;
import org.cdpg.dx.database.postgres.base.dao.BaseDAO;

public interface OrganizationHierarchyNodeDAO extends BaseDAO<OrganizationHierarchyNode> {

  Future<List<OrganizationHierarchyNode>> getByOrganizationId(UUID organizationId);

  Future<OrganizationHierarchyNode> getByIdAndOrganizationId(UUID nodeId, UUID organizationId);

  Future<List<OrganizationHierarchyNode>> getChildren(UUID organizationId, UUID parentId);

  Future<List<OrganizationHierarchyNode>> getDescendants(UUID organizationId, String path);

  /** Whether the organization has any hierarchy node, i.e. a defined department tree. */
  Future<Boolean> existsByOrganizationId(UUID organizationId);

  /**
   * Insert an entire precomputed tree in one SQL statement (no multi-statement
   * transaction primitive exists on {@code PostgresService}, so a loop of
   * single-row inserts would leave a partial tree on any mid-loop failure).
   *
   * <p>Every node in {@code nodes} must already carry a non-null {@code id}
   * (generated by the caller) and a {@code parentId} that is either {@code
   * null} (root) or the real {@code id} of another node in this same list --
   * callers must order {@code nodes} parent-before-child so the self-referencing
   * foreign key is satisfied row-by-row within the single statement.
   */
  Future<List<OrganizationHierarchyNode>> insertTree(List<OrganizationHierarchyNode> nodes);
}
